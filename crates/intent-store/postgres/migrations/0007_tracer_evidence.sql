-- T1 receipts and fences remain tenant-local and survive live workspace rows.
CREATE TABLE IF NOT EXISTS work_t1_evidence (
    tenant_id text NOT NULL,
    record_sequence bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    record_kind text NOT NULL,
    record_key text NOT NULL,
    payload_json text NOT NULL,
    owner_id text GENERATED ALWAYS AS (CASE WHEN record_kind='contribution' THEN payload_json::jsonb->>'bindingId' WHEN record_kind='admission' THEN payload_json::jsonb->>'agent' END) STORED,
    workspace_id text GENERATED ALWAYS AS (CASE WHEN record_kind='contribution' THEN payload_json::jsonb->'taskRevision'->>'workspaceId' WHEN record_kind='admission' THEN payload_json::jsonb->>'workspace' END) STORED,
    created_at text NOT NULL,
    PRIMARY KEY (tenant_id,record_sequence),
    UNIQUE (tenant_id,record_kind,record_key)
);
CREATE INDEX IF NOT EXISTS work_t1_evidence_owner ON work_t1_evidence(tenant_id,record_kind,owner_id,workspace_id,record_sequence);
CREATE OR REPLACE FUNCTION trg_work_t1_evidence_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' OR OLD.record_kind<>'active-binding'
      OR NEW.tenant_id IS DISTINCT FROM OLD.tenant_id
      OR NEW.record_kind IS DISTINCT FROM OLD.record_kind
      OR NEW.record_key IS DISTINCT FROM OLD.record_key
      OR NEW.record_sequence IS DISTINCT FROM OLD.record_sequence
      OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'T1 evidence records are immutable';
    END IF;
    RETURN NEW;
END
$$;
CREATE OR REPLACE TRIGGER work_t1_evidence_immutable BEFORE UPDATE OR DELETE ON work_t1_evidence
    FOR EACH ROW EXECUTE FUNCTION trg_work_t1_evidence_immutable();

CREATE TABLE IF NOT EXISTS work_t1_agent_fence (
    tenant_id text NOT NULL,
    agent_id text NOT NULL,
    workspace_id text NOT NULL,
    revision bigint NOT NULL CHECK(revision>0),
    assignment_revision bigint NOT NULL CHECK(assignment_revision>0),
    PRIMARY KEY (tenant_id,agent_id)
);
INSERT INTO work_t1_agent_fence (tenant_id,agent_id,workspace_id,revision,assignment_revision)
SELECT tenant_id,id,workspace_id,1,1 FROM agent_session
ON CONFLICT(tenant_id,agent_id) DO NOTHING;
CREATE OR REPLACE FUNCTION trg_work_t1_agent_fence() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='INSERT' THEN
        INSERT INTO work_t1_agent_fence (tenant_id,agent_id,workspace_id,revision,assignment_revision)
        VALUES(NEW.tenant_id,NEW.id,NEW.workspace_id,1,1)
        ON CONFLICT(tenant_id,agent_id) DO UPDATE SET workspace_id=EXCLUDED.workspace_id,
          revision=work_t1_agent_fence.revision+1,assignment_revision=work_t1_agent_fence.assignment_revision+1
          WHERE work_t1_agent_fence.tenant_id = NEW.tenant_id;
    ELSE
        UPDATE work_t1_agent_fence SET workspace_id=NEW.workspace_id,revision=revision+1,
          assignment_revision=assignment_revision+CASE WHEN OLD.task_note_id IS DISTINCT FROM NEW.task_note_id OR OLD.workspace_id IS DISTINCT FROM NEW.workspace_id THEN 1 ELSE 0 END
        WHERE work_t1_agent_fence.tenant_id = NEW.tenant_id AND agent_id=NEW.id;
    END IF;
    RETURN NEW;
END
$$;
CREATE OR REPLACE FUNCTION trg_work_t1_agent_fence_delete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE work_t1_agent_fence SET revision=revision+1,assignment_revision=assignment_revision+1
    WHERE work_t1_agent_fence.tenant_id = OLD.tenant_id AND agent_id=OLD.id;
    RETURN OLD;
END
$$;
CREATE OR REPLACE TRIGGER work_t1_agent_fence_insert AFTER INSERT ON agent_session
    FOR EACH ROW EXECUTE FUNCTION trg_work_t1_agent_fence();
CREATE OR REPLACE TRIGGER work_t1_agent_fence_update AFTER UPDATE OF status,is_active,retired_at,task_note_id,workspace_id ON agent_session
    FOR EACH ROW EXECUTE FUNCTION trg_work_t1_agent_fence();
CREATE OR REPLACE TRIGGER work_t1_agent_fence_delete AFTER DELETE ON agent_session
    FOR EACH ROW EXECUTE FUNCTION trg_work_t1_agent_fence_delete();
